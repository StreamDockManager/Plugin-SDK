#!/usr/bin/env python3
"""Generate/check SDK-embedded web helpers from their canonical web sources."""
import argparse
from sync_output import sync_output
import copy
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]

# Add Node type annotations without depending on initializer line wrapping
def typed_settings_core(core):
    typed = core.replace('function validateSettings(fields, settings, browser = false)',
                         'export function validateSettings(fields: any[], settings: Record<string, any>, browser = false): Record<string, any>')
    typed = typed.replace('function validateSettingsCore(fields, settings, browser, fail)', 'function validateSettingsCore(fields: any[], settings: Record<string, any>, browser: boolean, fail: (code: string, field?: any) => never): Record<string, any>')
    # Match declarations independently of formatter line breaks in their initializers
    typed = typed.replace('const common =', 'const common: Record<string, string> =').replace('const local =', 'const local: Record<string, string> =')
    return typed

# Run the sync assets command and enforce its input options
def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    core = (ROOT/'shared/settings-validation.js').read_text()
    typed = typed_settings_core(core)
    sync_output(ROOT/'Node/src/internal/settings-validation.ts',
                ('// Generated by tools/sync_assets.py; edit shared/settings-validation.js.\n'+typed).encode(),
                check=args.check, diagnostic='Run tools/sync_assets.py for settings validation')
    target = ROOT/'web/inspector-fields.js'
    wrapper = target.read_text()
    begin = '    // BEGIN GENERATED SETTINGS VALIDATION\n'
    end = '    // END GENERATED SETTINGS VALIDATION\n'
    prefix, remainder = wrapper.split(begin, 1)
    _, suffix = remainder.split(end, 1)
    expected = prefix + begin + ''.join('    '+line+'\n' if line else '\n' for line in core.splitlines()) + end + suffix
    sync_output(target, expected.encode(), check=args.check, diagnostic='Run tools/sync_assets.py for inspector validation')
    palette_path=ROOT/'web/palette.v1.json'
    palettes=json.loads(palette_path.read_text())['themes']
    derived={}
    for name in ('key','wide'):
        base=json.loads((ROOT/'web/display'/f'{name}.json').read_text())
        for theme,palette in palettes.items():
            value=copy.deepcopy(base)
            value['background']=palette['surface']
            for item in value['items']:
                item.update(color=palette['ink'],bar_fill_c=palette['accent'],bar_bg_c=palette['border'])
            derived[ROOT/'web/display'/f'{name}-{theme}.json']=(json.dumps(value,indent=4)+'\n').encode()
    icon=(ROOT/'web/icons/unavailable.svg').read_text()
    for theme,palette in palettes.items():
        derived[ROOT/'web/icons'/f'unavailable-{theme}.svg']=icon.replace('#f5f7fa',palette['ink']).encode()
    for target, data in derived.items():
        sync_output(target, data, check=args.check, diagnostic='Run tools/sync_assets.py')
    sync_output(ROOT/'examples/sdk-example-nodejs/counter.mjs',
                (ROOT/'examples/javascript/counter.mjs').read_bytes(),
                check=args.check, diagnostic='Run tools/sync_assets.py for Counter source')
    content={source.relative_to(ROOT/'web').as_posix():source.read_text() for source in (ROOT/'web').rglob('*') if source.is_file()}
    assets='// Generated by tools/sync_assets.py; edit canonical web sources.\nexport const content: Record<string,string> = '+json.dumps(content,ensure_ascii=False,sort_keys=True)+';\n'
    layouts='// Generated by tools/sync_assets.py; edit canonical web sources.\nexport const keyLayout = '+json.dumps(content['display/key.json'])+';\nexport const wideLayout = '+json.dumps(content['display/wide.json'])+';\n'
    for target,data in [(ROOT/'Node/src/inspector-assets.ts',assets),(ROOT/'Node/src/display-layouts.ts',layouts)]:
        sync_output(target, data.encode(), check=args.check, diagnostic='Run tools/sync_assets.py for JS assets')
    copies = [
        ('Python/stream_dock_manager_sdk/buildcache.py', 'examples/tools/buildcache.py', (b'from ._atomicfile import', b'from _atomicfile import')),
        ('Python/stream_dock_manager_sdk/_atomicfile.py', 'examples/tools/_atomicfile.py', None),
        ('examples/tools/authoring_common.py', 'Python/stream_dock_manager_sdk/authoring_common.py', None),
        ('Python/stream_dock_manager_sdk/packaging.py', 'examples/tools/audit.py', (b'from .authoring_common import', b'from authoring_common import')),
    ]
    for source, destination, rewrite in copies:
        data = (ROOT/source).read_bytes()
        if rewrite:
            data = data.replace(*rewrite)
        sync_output(ROOT/destination, data, check=args.check, diagnostic='Run tools/sync_assets.py')
    for source in (ROOT/'web').rglob('*'):
        if not source.is_file():continue
        for directory in ('Go/inspectors','Rust/web','Python/stream_dock_manager_sdk/web','examples/assets'):
            target=ROOT/directory/source.relative_to(ROOT/'web')
            sync_output(target, source.read_bytes(), check=args.check, diagnostic='Run tools/sync_assets.py')

if __name__=='__main__':main()
